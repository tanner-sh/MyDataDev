-- AI SQL Agent 评测用的固定库结构。
--
-- 刻意保留三处真实项目里常见的麻烦：
--   1. T_CRM_0021 的物理名毫无语义，只能靠表注释或业务词典找到；
--   2. APP_USER_ARCHIVE 是 APP_USER 的归档表，字段几乎一样，是最容易选错的干扰项；
--   3. 金额、时间、状态这些列名不统一（AMT / TOTAL_AMOUNT、CREATED_AT / ORDER_DATE），
--      模型不读真实字段就会猜错。
-- 改这里等于换了评测基线，历史分数不再可比 —— 要加用例优先加表，不要改已有表。

CREATE TABLE PRODUCT_CATEGORY (
    ID BIGINT PRIMARY KEY,
    CATEGORY_NAME VARCHAR(80) NOT NULL,
    PARENT_ID BIGINT
);
COMMENT ON TABLE PRODUCT_CATEGORY IS '商品类目';
COMMENT ON COLUMN PRODUCT_CATEGORY.CATEGORY_NAME IS '类目名称';
COMMENT ON COLUMN PRODUCT_CATEGORY.PARENT_ID IS '上级类目';

CREATE TABLE PRODUCT (
    ID BIGINT PRIMARY KEY,
    SKU VARCHAR(40) NOT NULL,
    PRODUCT_NAME VARCHAR(160) NOT NULL,
    CATEGORY_ID BIGINT,
    LIST_PRICE DECIMAL(12, 2),
    ON_SALE BOOLEAN,
    CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES PRODUCT_CATEGORY (ID)
);
COMMENT ON TABLE PRODUCT IS '商品主档';
COMMENT ON COLUMN PRODUCT.PRODUCT_NAME IS '商品名称';
COMMENT ON COLUMN PRODUCT.LIST_PRICE IS '标价';
COMMENT ON COLUMN PRODUCT.ON_SALE IS '是否在售';

CREATE TABLE T_CRM_0021 (
    ID BIGINT PRIMARY KEY,
    CUST_NM VARCHAR(120) NOT NULL,
    MOBILE VARCHAR(30),
    LEVEL_CD VARCHAR(10),
    ENABLED BOOLEAN,
    CREATED_AT TIMESTAMP
);
COMMENT ON TABLE T_CRM_0021 IS '客户主档';
COMMENT ON COLUMN T_CRM_0021.CUST_NM IS '客户名称';
COMMENT ON COLUMN T_CRM_0021.MOBILE IS '手机号';
COMMENT ON COLUMN T_CRM_0021.LEVEL_CD IS '客户等级';
COMMENT ON COLUMN T_CRM_0021.ENABLED IS '是否启用';
COMMENT ON COLUMN T_CRM_0021.CREATED_AT IS '建档时间';

CREATE TABLE APP_USER (
    ID BIGINT PRIMARY KEY,
    LOGIN_NAME VARCHAR(80) NOT NULL,
    DISPLAY_NAME VARCHAR(120),
    DEPARTMENT VARCHAR(80),
    ACTIVE BOOLEAN,
    LAST_LOGIN_AT TIMESTAMP
);
COMMENT ON TABLE APP_USER IS '系统用户，销售员也在这张表里';
COMMENT ON COLUMN APP_USER.DISPLAY_NAME IS '姓名';
COMMENT ON COLUMN APP_USER.DEPARTMENT IS '所属部门';
COMMENT ON COLUMN APP_USER.ACTIVE IS '是否在职';
COMMENT ON COLUMN APP_USER.LAST_LOGIN_AT IS '最后登录时间';

CREATE TABLE APP_USER_ARCHIVE (
    ID BIGINT PRIMARY KEY,
    LOGIN_NAME VARCHAR(80),
    DISPLAY_NAME VARCHAR(120),
    DEPARTMENT VARCHAR(80),
    ARCHIVED_AT TIMESTAMP
);
COMMENT ON TABLE APP_USER_ARCHIVE IS '离职用户归档，不参与任何在用统计';

CREATE TABLE SALES_ORDER (
    ID BIGINT PRIMARY KEY,
    ORDER_NO VARCHAR(40) NOT NULL,
    CUSTOMER_ID BIGINT NOT NULL,
    SALES_REP_ID BIGINT,
    TOTAL_AMOUNT DECIMAL(14, 2),
    ORDER_STATUS VARCHAR(20),
    ORDER_DATE TIMESTAMP,
    CONSTRAINT FK_ORDER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES T_CRM_0021 (ID),
    CONSTRAINT FK_ORDER_SALES_REP FOREIGN KEY (SALES_REP_ID) REFERENCES APP_USER (ID)
);
COMMENT ON TABLE SALES_ORDER IS '销售订单';
COMMENT ON COLUMN SALES_ORDER.ORDER_NO IS '订单号';
COMMENT ON COLUMN SALES_ORDER.CUSTOMER_ID IS '客户';
COMMENT ON COLUMN SALES_ORDER.SALES_REP_ID IS '销售员';
COMMENT ON COLUMN SALES_ORDER.TOTAL_AMOUNT IS '订单总金额';
COMMENT ON COLUMN SALES_ORDER.ORDER_STATUS IS '订单状态：DRAFT/PAID/SHIPPED/CANCELLED';
COMMENT ON COLUMN SALES_ORDER.ORDER_DATE IS '下单时间';

CREATE TABLE SALES_ORDER_ITEM (
    ID BIGINT PRIMARY KEY,
    ORDER_ID BIGINT NOT NULL,
    PRODUCT_ID BIGINT NOT NULL,
    QTY INT,
    AMT DECIMAL(14, 2),
    CONSTRAINT FK_ITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES SALES_ORDER (ID),
    CONSTRAINT FK_ITEM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (ID)
);
COMMENT ON TABLE SALES_ORDER_ITEM IS '订单明细';
COMMENT ON COLUMN SALES_ORDER_ITEM.QTY IS '数量';
COMMENT ON COLUMN SALES_ORDER_ITEM.AMT IS '明细金额';

CREATE TABLE PAYMENT (
    ID BIGINT PRIMARY KEY,
    ORDER_ID BIGINT NOT NULL,
    PAID_AMOUNT DECIMAL(14, 2),
    PAY_CHANNEL VARCHAR(20),
    PAID_AT TIMESTAMP,
    CONSTRAINT FK_PAYMENT_ORDER FOREIGN KEY (ORDER_ID) REFERENCES SALES_ORDER (ID)
);
COMMENT ON TABLE PAYMENT IS '支付流水';
COMMENT ON COLUMN PAYMENT.PAID_AMOUNT IS '实付金额';
COMMENT ON COLUMN PAYMENT.PAY_CHANNEL IS '支付渠道';
COMMENT ON COLUMN PAYMENT.PAID_AT IS '支付时间';
