package db.migration;

import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/**
 * 异构数据库完整迁移与标准制品（.mddpkg）持久化表结构：
 * <ul>
 *   <li>{@code migration_artifact}：导出或上传的标准制品元数据；</li>
 *   <li>{@code migration_job}：迁移任务总览（在线直迁 / 导出制品 / 导入制品）；</li>
 *   <li>{@code migration_item}：表/对象级执行项、断点续传检查点与校验结果。</li>
 * </ul>
 */
public class V31__DatabaseMigration extends BaseJavaMigration {
    @Override
    public void migrate(Context context) throws Exception {
        try (var statement = context.getConnection().createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS migration_artifact (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(255) NOT NULL,
                        file_path VARCHAR(1024) NOT NULL,
                        storage_profile_id BIGINT,
                        remote_path VARCHAR(1024),
                        file_size BIGINT NOT NULL DEFAULT 0,
                        checksum VARCHAR(128) NOT NULL,
                        source_db_type VARCHAR(64) NOT NULL,
                        source_version VARCHAR(255),
                        source_schema VARCHAR(255),
                        format_version INT NOT NULL DEFAULT 1,
                        table_count INT NOT NULL DEFAULT 0,
                        total_rows BIGINT NOT NULL DEFAULT 0,
                        total_bytes BIGINT NOT NULL DEFAULT 0,
                        manifest_json CLOB,
                        owner_user_id BIGINT,
                        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        expires_at TIMESTAMP
                    )""");
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS migration_job (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        mode VARCHAR(32) NOT NULL,
                        source_kind VARCHAR(32) NOT NULL,
                        source_connection_id BIGINT,
                        source_artifact_id BIGINT,
                        source_db_type VARCHAR(64) NOT NULL,
                        source_schema VARCHAR(255),
                        target_connection_id BIGINT,
                        target_db_type VARCHAR(64),
                        target_schema VARCHAR(255),
                        output_artifact_id BIGINT,
                        conflict_mode VARCHAR(32) NOT NULL DEFAULT 'FAIL',
                        options_json CLOB,
                        assessment_json CLOB,
                        snapshot_token VARCHAR(255),
                        status VARCHAR(32) NOT NULL,
                        phase VARCHAR(64) NOT NULL,
                        total_items INT NOT NULL DEFAULT 0,
                        completed_items INT NOT NULL DEFAULT 0,
                        failed_items INT NOT NULL DEFAULT 0,
                        total_rows BIGINT NOT NULL DEFAULT 0,
                        migrated_rows BIGINT NOT NULL DEFAULT 0,
                        migrated_bytes BIGINT NOT NULL DEFAULT 0,
                        verify_status VARCHAR(32) NOT NULL DEFAULT 'NOT_RUN',
                        verify_report_json CLOB,
                        message VARCHAR(2000),
                        cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
                        actor VARCHAR(120),
                        owner_user_id BIGINT,
                        started_at TIMESTAMP,
                        finished_at TIMESTAMP,
                        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )""");
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS migration_item (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        job_id BIGINT NOT NULL,
                        item_kind VARCHAR(32) NOT NULL,
                        source_name VARCHAR(255) NOT NULL,
                        target_name VARCHAR(255) NOT NULL,
                        table_id VARCHAR(128),
                        execution_order INT NOT NULL DEFAULT 0,
                        status VARCHAR(32) NOT NULL,
                        source_rows BIGINT NOT NULL DEFAULT 0,
                        migrated_rows BIGINT NOT NULL DEFAULT 0,
                        migrated_bytes BIGINT NOT NULL DEFAULT 0,
                        total_parts INT NOT NULL DEFAULT 0,
                        completed_parts INT NOT NULL DEFAULT 0,
                        checkpoint_json CLOB,
                        ddl_json CLOB,
                        warnings_json CLOB,
                        verify_status VARCHAR(32) NOT NULL DEFAULT 'NOT_RUN',
                        verify_detail_json CLOB,
                        error_message VARCHAR(4000),
                        started_at TIMESTAMP,
                        finished_at TIMESTAMP,
                        CONSTRAINT fk_migration_item_job FOREIGN KEY (job_id) REFERENCES migration_job(id) ON DELETE CASCADE
                    )""");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_migration_job_created ON migration_job (created_at DESC, id DESC)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_migration_job_status ON migration_job (status)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_migration_item_job_order ON migration_item (job_id, execution_order, id)");
        }
    }
}
